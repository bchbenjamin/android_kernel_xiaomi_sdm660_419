#!/usr/bin/env bash
set -euo pipefail
config=${1:-.config}
if [[ ! -f "$config" ]]; then
  echo "usage: $0 path/to/.config" >&2
  exit 2
fi
required=(
  CONFIG_SYSCTL CONFIG_SYSVIPC CONFIG_POSIX_MQUEUE
  CONFIG_NAMESPACES CONFIG_PID_NS CONFIG_UTS_NS CONFIG_IPC_NS
  CONFIG_SECCOMP CONFIG_SECCOMP_FILTER
  CONFIG_CGROUPS CONFIG_CGROUP_DEVICE CONFIG_CGROUP_SCHED
  CONFIG_FAIR_GROUP_SCHED CONFIG_CGROUP_FREEZER CONFIG_CGROUP_NET_PRIO
  CONFIG_MEMCG CONFIG_MEMCG_SWAP CONFIG_MEMCG_SWAP_ENABLED
  CONFIG_CFS_BANDWIDTH CONFIG_CGROUP_PIDS CONFIG_CGROUP_CPUACCT
  CONFIG_DEVTMPFS CONFIG_OVERLAY_FS CONFIG_TMPFS_POSIX_ACL CONFIG_TMPFS_XATTR
  CONFIG_FW_LOADER CONFIG_FW_LOADER_USER_HELPER
  CONFIG_NET_NS CONFIG_VETH CONFIG_BRIDGE CONFIG_NETFILTER CONFIG_BRIDGE_NETFILTER
  CONFIG_NETFILTER_ADVANCED CONFIG_NF_CONNTRACK CONFIG_NF_CT_NETLINK
  CONFIG_IP_NF_IPTABLES CONFIG_IP_NF_FILTER CONFIG_NF_NAT CONFIG_NF_TABLES
  CONFIG_IP_NF_TARGET_MASQUERADE CONFIG_NETFILTER_XT_TARGET_TCPMSS
  CONFIG_NETFILTER_XT_MATCH_ADDRTYPE CONFIG_NF_NAT_REDIRECT
  CONFIG_IP_ADVANCED_ROUTER CONFIG_IP_MULTIPLE_TABLES CONFIG_NF_NAT_IPV4
  CONFIG_IP_NF_NAT CONFIG_IPV6 CONFIG_IPV6_MULTIPLE_TABLES
  CONFIG_IP6_NF_IPTABLES CONFIG_IP6_NF_FILTER CONFIG_IP6_NF_MANGLE
  CONFIG_IP6_NF_NAT CONFIG_IP6_NF_TARGET_MASQUERADE CONFIG_NF_NAT_IPV6
  CONFIG_MACVLAN CONFIG_USER_NS
)
failed=0
for symbol in "${required[@]}"; do
  if ! grep -Fxq "${symbol}=y" "$config"; then
    echo "MISSING: ${symbol}=y"
    failed=1
  fi
done
if ! grep -Fxq '# CONFIG_ANDROID_PARANOID_NETWORK is not set' "$config"; then
  echo 'MISSING: CONFIG_ANDROID_PARANOID_NETWORK=n'
  failed=1
fi
if (( failed )); then
  exit 1
fi
echo "PASS: all supported required DroidSpaces options are enabled"
echo "NOTE: legacy/renamed symbols are documented in README; this check uses this tree's Kconfig names."
